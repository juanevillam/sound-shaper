const fs = require('fs');
const path = require('path');

const {
  IOSConfig,
  withDangerousMod,
  withInfoPlist,
  withXcodeProject,
} = require('expo/config-plugins');

const FILE_NAME = 'SceneDelegate.swift';
const CONFIGURATION_NAME = 'Default Configuration';

/**
 * A minimal `UIWindowSceneDelegate` for an app whose window is still built by
 * the APP delegate.
 *
 * iOS 27 / the iOS 26+ SDK made UIScene adoption mandatory: an app linked
 * against it that has not adopted traps at launch inside
 * `_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption`
 * (EXC_BREAKPOINT / SIGTRAP on the main thread, before any JS runs). React
 * Native 0.86 and Expo SDK 57 have no scene adoption of their own — neither
 * ships a scene delegate or a manifest — so this supplies the smallest one that
 * satisfies UIKit without moving RN's own startup.
 *
 * WHY IT ADOPTS THE EXISTING WINDOW RATHER THAN MAKING ONE. Expo's
 * `AppDelegate.swift` still creates `window` and calls
 * `factory.startReactNative(withModuleName:in:launchOptions:)` from
 * `didFinishLaunchingWithOptions`, which runs BEFORE `scene(_:willConnectTo:)`.
 * Building a second window here would leave React Native rendering into an
 * orphan and the screen black. So the scene takes the window that already
 * exists and only gives it a `windowScene`.
 *
 * WHAT WOULD BREAK SILENTLY WITHOUT THE FORWARDING BELOW: once an app is
 * scene-based, UIKit STOPS calling `application(_:open:options:)` and
 * `application(_:continue:restorationHandler:)` on the app delegate and
 * delivers those to the scene instead. Every deep link in this portfolio is
 * handled app-delegate-side (`RCTLinkingManager`, expo-router, Google Sign-In's
 * callback, and Sound Shaper's `soundshaper://home?play=<id>` widget taps), so
 * each entry point is forwarded back rather than reimplemented — including the
 * COLD-LAUNCH case, which arrives in `connectionOptions` and nowhere else.
 */
const SCENE_DELEGATE_SWIFT = `import UIKit

// @generated by plugins/with-ios-scene-lifecycle.js — do not edit by hand.
//
// See that plugin for why this exists and why it adopts the app delegate's
// window instead of creating its own.
@objc(SceneDelegate)
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  private var appDelegate: UIApplicationDelegate? {
    UIApplication.shared.delegate
  }

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard let windowScene = scene as? UIWindowScene else { return }

    // React Native is already running and its window already exists — it was
    // built in \`didFinishLaunchingWithOptions\`, which precedes this callback.
    // Attach it to the scene rather than standing a second one.
    if let existing = appDelegate?.window ?? nil {
      existing.windowScene = windowScene
      window = existing
      existing.makeKeyAndVisible()
    }

    // A COLD launch from a link delivers it here and never through
    // \`scene(_:openURLContexts:)\`, so both paths are needed.
    open(urlContexts: connectionOptions.urlContexts)
    for activity in connectionOptions.userActivities {
      continueActivity(activity)
    }
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    open(urlContexts: URLContexts)
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    continueActivity(userActivity)
  }

  private func open(urlContexts: Set<UIOpenURLContext>) {
    guard let delegate = appDelegate else { return }
    for context in urlContexts {
      var options: [UIApplication.OpenURLOptionsKey: Any] = [:]
      if let source = context.options.sourceApplication {
        options[.sourceApplication] = source
      }
      if let annotation = context.options.annotation {
        options[.annotation] = annotation
      }
      _ = delegate.application?(UIApplication.shared, open: context.url, options: options)
    }
  }

  private func continueActivity(_ userActivity: NSUserActivity) {
    guard let delegate = appDelegate else { return }
    _ = delegate.application?(
      UIApplication.shared,
      continue: userActivity,
      restorationHandler: { _ in }
    )
  }
}
`;

/** The manifest UIKit reads to decide whether the app adopted scenes at all. */
const withSceneManifest = config =>
  withInfoPlist(config, cfg => {
    // `$(PRODUCT_MODULE_NAME)` rather than a literal: the Swift class is
    // namespaced by the module, and the module name is the app's, which differs
    // per app in this monorepo.
    cfg.modResults.UIApplicationSceneManifest = {
      UIApplicationSupportsMultipleScenes: false,
      UISceneConfigurations: {
        UIWindowSceneSessionRoleApplication: [
          {
            UISceneConfigurationName: CONFIGURATION_NAME,
            UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
          },
        ],
      },
    };
    return cfg;
  });

/** Write the Swift file next to the generated AppDelegate. */
const withSceneDelegateFile = config =>
  withDangerousMod(config, [
    'ios',
    cfg => {
      const name = cfg.modRequest.projectName;
      if (!name) {
        throw new Error(
          '[with-ios-scene-lifecycle] no projectName on the mod request',
        );
      }
      const target = path.join(
        cfg.modRequest.platformProjectRoot,
        name,
        FILE_NAME,
      );
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, SCENE_DELEGATE_SWIFT);
      return cfg;
    },
  ]);

/**
 * Add it to the app target's Compile Sources.
 *
 * Writing the file is not enough — `ios/` is regenerated by every prebuild and
 * the pbxproj is regenerated with it, so an un-referenced .swift compiles into
 * nothing and the manifest above then names a class that does not exist, which
 * fails at launch exactly as the missing manifest did.
 */
const withSceneDelegateBuildFile = config =>
  withXcodeProject(config, cfg => {
    const name = cfg.modRequest.projectName;
    const project = cfg.modResults;
    const group = `${name}/${FILE_NAME}`;

    if (project.hasFile(group)) return cfg;

    IOSConfig.XcodeUtils.addBuildSourceFileToGroup({
      filepath: group,
      groupName: name,
      project,
    });
    return cfg;
  });

/**
 * iOS 27 traps at launch on an app that has not adopted the UIScene lifecycle.
 * RN 0.86 / Expo 57 have not, so this adds the manifest AND the delegate class
 * it names — both halves are required, and either alone still traps.
 */
const withIosSceneLifecycle = config =>
  withSceneDelegateBuildFile(withSceneDelegateFile(withSceneManifest(config)));

module.exports = withIosSceneLifecycle;
